// The licence manifest (roadmap A6-T9): licenses/components.json (kept by hand: tools, models, the host) plus the npm
// packages the plugin runs with (from package-lock.json) and the decider's Python environment (read from an installed
// environment's metadata), written as licenses/third-party.json and THIRD_PARTY.md.
//
//   node scripts/third-party.mjs [--venv <decider .venv>]   write both files
//   node scripts/third-party.mjs --check                     exit 1 when the npm or component part is out of date
//
// The Python part needs an installed decider (omacode-services, the Coding profile); without one it keeps the list the
// manifest already has, so a run on a machine without services does not drop it. --check compares the parts every
// machine can rebuild (components and npm), never the Python part.

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { homedir } from "node:os"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const MANIFEST = join(ROOT, "licenses", "third-party.json")
const MARKDOWN = join(ROOT, "THIRD_PARTY.md")

// The npm packages installed for production: not dev-only, not a workspace link.
export function npmPackages(lock) {
  return Object.entries(lock.packages ?? {})
    .filter(([key, p]) => key.startsWith("node_modules/") && !p.dev && !p.devOptional && !p.link)
    .map(([key, p]) => ({ name: key.slice(key.lastIndexOf("node_modules/") + "node_modules/".length), version: p.version, spdx: p.license ?? "UNKNOWN" }))
    .sort((a, b) => a.name.localeCompare(b.name))
}

// One dist-info's licence: the SPDX expression when the package gives one, else its License field, else its classifiers.
function pythonLicence(metadata) {
  const field = (name) => new RegExp(`^${name}: (.*)$`, "m").exec(metadata)?.[1]?.trim()
  const classifiers = [...metadata.matchAll(/^Classifier: License :: (.*)$/gm)].map((m) => m[1].split(" :: ").pop())
  const license = field("License")
  return field("License-Expression") ?? (license && license.length <= 80 ? license : undefined) ?? (classifiers.join(" / ") || "UNKNOWN")
}

export function pythonPackages(venv) {
  const lib = join(venv, "lib")
  if (!existsSync(lib)) return undefined
  const out = []
  for (const py of readdirSync(lib)) {
    const site = join(lib, py, "site-packages")
    if (!existsSync(site)) continue
    for (const d of readdirSync(site).filter((x) => x.endsWith(".dist-info"))) {
      const metadata = readFileSync(join(site, d, "METADATA"), "utf8")
      const name = /^Name: (.*)$/m.exec(metadata)?.[1]?.trim()
      const version = /^Version: (.*)$/m.exec(metadata)?.[1]?.trim()
      if (!name || name === "decider") continue // the decider itself is omacode's own code
      out.push({ name, version, spdx: pythonLicence(metadata) })
    }
  }
  return out.sort((a, b) => a.name.toLowerCase().localeCompare(b.name.toLowerCase()))
}

export function build({ components, lock, python }) {
  return {
    about: "Generated by scripts/third-party.mjs from licenses/components.json, package-lock.json and the decider's Python environment. Edit components.json, not this file.",
    components: components.components,
    npm: npmPackages(lock),
    python: python ?? [],
  }
}

const cell = (s) => String(s ?? "").replace(/\|/g, "\\|")

export function markdown(manifest) {
  const lines = [
    "# Third-party software",
    "",
    "What omacode installs, downloads or relies on, under which licence, and what that means for what you make with it.",
    "Generated by `node scripts/third-party.mjs` from `licenses/components.json`; the machine-readable form is",
    "`licenses/third-party.json`. Image models you add yourself are not listed here: the model registry",
    "(`npm run models -- status`) holds their licences, and the plugin checks them before every ComfyUI run.",
    "",
    "**Installed by:** `minimal`, `coding`, `creator`, `full` are the install.sh profiles; `downloaded` is fetched on first",
    "use by something installed; `you` is needed but not installed by omacode; `planned` is not installed yet.",
    "**Telemetry:** what a tool reports to its maker on its own. omacode sets DO_NOT_TRACK=1, HYPERFRAMES_NO_TELEMETRY=1 and",
    "DISABLE_TELEMETRY=1 for everything it starts and for every agent shell (`packages/core/src/telemetry.ts`).",
    "",
    "## Programs and models",
    "",
    "| Name | Version | Licence | Installed by | Where | Commercial use of what you make | When you pass it on | Telemetry |",
    "|---|---|---|---|---|---|---|---|",
    ...manifest.components.map((c) => `| ${cell(c.name)}${c.notes ? `<br><sub>${cell(c.notes)}</sub>` : ""} | ${cell(c.version ?? "")} | \`${cell(c.spdx)}\` | ${cell(c.installedBy)} | ${cell(c.territory)} | ${cell(c.commercialOutput)} | ${cell(c.attribution)} | ${cell(c.telemetry ?? "not checked")} |`),
    "",
    "## npm packages the plugin runs with",
    "",
    "| Package | Version | Licence |",
    "|---|---|---|",
    ...manifest.npm.map((p) => `| ${cell(p.name)} | ${cell(p.version)} | \`${cell(p.spdx)}\` |`),
    "",
    "## The decider's Python environment (omacode-services)",
    "",
    ...(manifest.python.length
      ? ["Pinned by `decider/uv.lock`; read from an installed environment.", "", "| Package | Version | Licence |", "|---|---|---|", ...manifest.python.map((p) => `| ${cell(p.name)} | ${cell(p.version)} | \`${cell(p.spdx)}\` |`)]
      : ["Not listed: generate this file on a machine with omacode-services installed."]),
    "",
  ]
  return lines.join("\n")
}

const readJson = (file) => JSON.parse(readFileSync(file, "utf8"))

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2)
  const components = readJson(join(ROOT, "licenses", "components.json"))
  const lock = readJson(join(ROOT, "package-lock.json"))
  const previous = existsSync(MANIFEST) ? readJson(MANIFEST) : undefined
  if (args.includes("--check")) {
    const fresh = build({ components, lock, python: previous?.python })
    const stale = !previous || JSON.stringify(previous.components) !== JSON.stringify(fresh.components) || JSON.stringify(previous.npm) !== JSON.stringify(fresh.npm)
    if (stale) {
      console.error("licenses/third-party.json is out of date: run node scripts/third-party.mjs")
      process.exit(1)
    }
    console.log("licence manifest is up to date")
    process.exit(0)
  }
  const at = args.indexOf("--venv")
  const venv = at >= 0 ? args[at + 1] : join(process.env.XDG_DATA_HOME || join(homedir(), ".local", "share"), "omacode", "services", "decider", ".venv")
  const python = pythonPackages(venv) ?? previous?.python
  const manifest = build({ components, lock, python })
  writeFileSync(MANIFEST, `${JSON.stringify(manifest, null, 2)}\n`)
  writeFileSync(MARKDOWN, markdown(manifest))
  console.log(`wrote ${MANIFEST} and ${MARKDOWN}: ${manifest.components.length} components, ${manifest.npm.length} npm, ${manifest.python.length} Python packages`)
}
